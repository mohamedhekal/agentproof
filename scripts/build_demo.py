#!/usr/bin/env python3
"""Build docs/demo/bundle.json: the real AgentProof source + data the browser demo needs.

    python scripts/build_demo.py           # regenerate the bundle
    python scripts/build_demo.py --check   # fail if the committed bundle is stale (CI runs this via the tests)

The demo runs the *actual* package inside Pyodide, so the bundle is just a copy of src/agentproof, the
glue module and two data files. `--check` guarantees the page can never drift from the code it explains.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "demo" / "bundle.json"


def build() -> str:
    files: dict[str, str] = {}
    for p in sorted((ROOT / "src" / "agentproof").rglob("*.py")):
        files[f"py/{p.relative_to(ROOT / 'src').as_posix()}"] = p.read_text(encoding="utf-8")
    files["py/demo_api.py"] = (ROOT / "docs" / "demo" / "demo_api.py").read_text(encoding="utf-8")
    files["cassettes/claude.jsonl"] = (ROOT / "cassettes" / "claude.jsonl").read_text(encoding="utf-8")
    return json.dumps({"about": "generated by scripts/build_demo.py; do not edit by hand", "files": files}, ensure_ascii=False, indent=0) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("demo bundle is up to date" if ok else "demo bundle is STALE: run `python scripts/build_demo.py` and commit docs/demo/bundle.json")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB, {len(json.loads(text)['files'])} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
